/**
 * Расписание КНИТУ-КАИ (осенний семестр 2026/2027).
 * В КАИ расписание задаётся списком конкретных дат, а не периодом + чётностью,
 * поэтому используется поле `dates`. Длительность пары — 90 минут.
 */

/** '07.09 21.09' → ['2026-09-07', '2026-09-21'] */
const D = (s) =>
  s.trim().split(/\s+/).map((d) => {
    const [dd, mm] = d.split('.')
    return `2026-${mm}-${dd}`
  })

const PLACES = {
  'КСК / ОЛИМП': { building: 'Спорткомплекс КСК КАИ ОЛИМП', room: '' },
  'ДОТ / ДОТ': { building: 'Дистанционно (ДОТ)', room: '', online: true },
}

function place(code) {
  if (PLACES[code]) return PLACES[code]
  const [b, r] = code.split('/').map((x) => x.trim())
  return { building: `Здание №${b}`, room: r }
}

const KINDS = { 'лек': 'лекция', 'пр': 'практика', 'л.р.': 'лаб. работа' }

const l = (start, title, kind, placeCode, teacher, dept, dates, category) => ({
  start,
  title,
  kind,
  kindFull: KINDS[kind] ?? kind,
  teacher,
  department: dept,
  ...place(placeCode),
  dates: D(dates),
  category,
})

